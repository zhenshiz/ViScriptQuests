package com.viscriptquests.quest.data.runtime;

/**
 * 定义单个小任务目标在玩家任务进度中的生命周期状态。
 *
 * <p>状态随 {@link TaskObjectiveProgress} 持久化，并由服务端的目标提交与任务流程逻辑维护。
 * 正常的顺序目标按照 {@link #LOCKED}、{@link #ACTIVE}、{@link #COMPLETED} 的方向推进；
 * 未被选择的分支、未完成的可选目标或被提前结束的目标会进入 {@link #SKIPPED}。
 * 小任务重新进入流程时可以根据最新的任务定义重建目标状态。
 */
public enum ObjectiveStatus {
    /**
     * 尚未被目标流程解锁的状态。
     *
     * <p>该状态的目标不会检测玩家行为，不接受自动或手动提交，也不会显示在任务书、
     * 追踪 HUD 或导航标记中。锁定目标本身不阻塞小任务完成；当前置目标完成并触发对应的
     * 激活动作后，该目标进入 {@link #ACTIVE}。
     */
    LOCKED,

    /**
     * 已解锁并正在等待玩家完成的状态。
     *
     * <p>该状态的目标会参与进度检测和完成判定，并在允许展示时出现在任务书和追踪 HUD 中。
     * 目标满足完成条件后进入 {@link #COMPLETED}；如果所在分支被放弃或小任务提前结束，
     * 则进入 {@link #SKIPPED}。
     */
    ACTIVE,

    /**
     * 已满足完成条件的终止状态。
     *
     * <p>该状态的目标不再重复检测或提交，并视为已经满足小任务的对应完成要求。
     * 目标仍可在任务书中展示完成记录，但不会继续显示在追踪 HUD 中；Ponder 等可重复查看的
     * 附加操作可以继续保留，不会因此再次完成目标或重复触发奖励。
     */
    COMPLETED,

    /**
     * 已被任务流程放弃的终止状态。
     *
     * <p>该状态用于未选中的条件分支、小任务结算时尚未完成的可选目标，以及任务结束时不再需要
     * 处理的目标。跳过目标不会继续检测、提交或显示，也不会阻塞小任务完成；已经进入
     * {@link #COMPLETED} 的目标不会再被改为该状态。
     */
    SKIPPED
}
